test('bhavadhara: approved organisations grouped by country, search and filters', async ({ page }) => {
  await page.goto('/bhavadhara')
  await expect(page.locator('.bd-country h2')).toHaveText([/Bangladesh/, /Testland/])
  await expect(page.getByText('Pending Org Must Not Show')).toHaveCount(0)
  await page.getByPlaceholder('Search by name, city or country').fill('zeta')
  await expect(page.locator('.bd-card h3')).toHaveText(['Test Vedanta Centre Zeta'])
  await page.getByPlaceholder('Search by name, city or country').fill('')
  await page.getByLabel('Kind of organisation').selectOption('ashram')
  await expect(page.locator('.bd-card h3')).toHaveText(['Test Ashram Omega'])
})

test('bhavadhara: a visitor adds an organisation, saved as pending', async ({ page, db }) => {
  await page.goto('/bhavadhara')
  await page.locator('.bd-hero').getByRole('button', { name: 'Add an organisation' }).click()
  const form = page.locator('#bd-form')
  await form.getByRole('button', { name: 'Send for listing' }).click()
  await expect(form.getByText('Please confirm the details.')).toBeVisible()
  await form.getByLabel('Organisation name (English) *').fill('Test Vedanta Centre Zeta')
  await form.getByLabel('Country *').fill('Testland')
  await form.getByLabel('Website (optional)').fill('example.org')
  await form.getByLabel('Your name *').fill('Sender Name')
  await form.getByLabel('Your email *').fill('sender@example.com')
  await form.getByLabel('The details are correct and may be shown on this website.').check()
  await form.getByRole('button', { name: 'Send for listing' }).click()
  await expect(form.getByText('This organisation is already in the directory.')).toBeVisible()
  await expect(form.getByText('Enter the full website address, starting with https://')).toBeVisible()
  await form.getByLabel('Organisation name (English) *').fill('Brand New Test Mission')
  await form.getByLabel('Website (optional)').fill('https://new.example.org')
  await form.getByRole('button', { name: 'Send for listing' }).click()
  await expect(page.getByText('Thank you. The organisation will be listed after the Samiti checks it.')).toBeVisible()
  const org = db.writes.find(w => w.table === 'bhavadhara_orgs')
  expect(org.body).toMatchObject({ name_en: 'Brand New Test Mission', country: 'Testland', status: 'pending', website: 'https://new.example.org' })
  expect(db.writes.find(w => w.table === 'submission_contacts').body).toMatchObject({ kind: 'bhavadhara', ref_id: org.body.id, email: 'sender@example.com' })
})

