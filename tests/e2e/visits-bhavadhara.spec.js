// Holy Visits (/visits) and the Bhavadhara directory (/bhavadhara)
import { test, expect, chooseLanguage } from './fixtures.js'

test('holy visits: published visits newest first, approved memories only', async ({ page }) => {
  await page.goto('/visits')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Holy Visits')
  const names = page.locator('.hv-visit h2')
  await expect(names).toHaveText(['Test Swami Alpha Maharaj', 'Test Swami Beta Maharaj'])
  await expect(page.getByText('Hidden Draft Visit')).toHaveCount(0)
  const first = page.locator('#visit-vi-1')
  await expect(first.getByText('Test blessing words.')).toBeVisible()
  await expect(first.getByRole('link', { name: 'Sree Sree Ramakrishna Mandir' })).toHaveAttribute('href', '/org/ramakrishna')
  await expect(first.getByText('An approved test memory of the visit.')).toBeVisible()
  await expect(page.getByText('A PENDING MEMORY THAT MUST NOT SHOW.')).toHaveCount(0)
})

test('holy visits: a devotee sends a memory, saved as pending with a private contact', async ({ page, db }) => {
  await page.goto('/visits')
  const visit = page.locator('#visit-vi-2')
  await visit.getByRole('button', { name: 'Share your memory' }).click()
  await visit.getByRole('button', { name: 'Send memory' }).click()
  await expect(visit.getByText('Please write your memory (20–3000 characters).')).toBeVisible()
  await visit.getByLabel('Full name *').fill('New Writer')
  await visit.getByLabel('Email or phone (optional, private)').fill('writer@example.com')
  await visit.getByLabel('Your memory *').fill('I remember the gentle smile and the words he spoke to us.')
  await visit.getByRole('button', { name: 'Send memory' }).click()
  await expect(visit.getByText('Thank you. Your memory will appear here after the Samiti reads it.')).toBeVisible()
  const memory = db.writes.find(w => w.table === 'visit_memories')
  expect(memory.body).toMatchObject({ visit_id: 'vi-2', author_name: 'New Writer', status: 'pending' })
  expect(memory.body).not.toHaveProperty('email')
  const contact = db.writes.find(w => w.table === 'submission_contacts')
  expect(contact.body).toMatchObject({ kind: 'memory', ref_id: memory.body.id, email: 'writer@example.com' })
})

